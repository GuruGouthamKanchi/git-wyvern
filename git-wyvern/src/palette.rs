#[derive(Clone, Copy, Debug)]
pub struct Rgba(pub u8, pub u8, pub u8, pub u8);

impl Rgba {
    pub const fn new(r: u8, g: u8, b: u8, a: u8) -> Self {
        Rgba(r, g, b, a)
    }
    pub const fn rgb(r: u8, g: u8, b: u8) -> Self {
        Rgba(r, g, b, 255)
    }
    pub const TRANSPARENT: Self = Rgba(0, 0, 0, 0);

    /// Continuous linear interpolation between two RGBA colors
    #[inline]
    pub fn lerp(self, other: Rgba, t: f32) -> Rgba {
        let t = t.clamp(0.0, 1.0);
        let r = (self.0 as f32 * (1.0 - t) + other.0 as f32 * t).round() as u8;
        let g = (self.1 as f32 * (1.0 - t) + other.1 as f32 * t).round() as u8;
        let b = (self.2 as f32 * (1.0 - t) + other.2 as f32 * t).round() as u8;
        let a = (self.3 as f32 * (1.0 - t) + other.3 as f32 * t).round() as u8;
        Rgba(r, g, b, a)
    }
}

